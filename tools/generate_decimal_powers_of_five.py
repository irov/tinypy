#!/usr/bin/env python
from __future__ import print_function

import sys


MIN_EXPONENT = -342
MAX_EXPONENT = 308


def power_of_five_significand(exponent):
    # The 128-bit significand of 5^exponent used by the Eisel-Lemire
    # algorithm (Lemire, "Number Parsing at a Gigabyte per Second", 2021).
    if exponent < 0:
        power = 5 ** -exponent
        width = power.bit_length()
        if exponent >= -27:
            value = (1 << (width + 127)) // power + 1
        else:
            value = (1 << (2 * width + 128)) // power + 1
            while value >= 1 << 128:
                value >>= 1
    else:
        value = 5 ** exponent
        while value < 1 << 127:
            value <<= 1
        while value >= 1 << 128:
            value >>= 1
    assert (1 << 127) <= value < (1 << 128)
    return value >> 64, value & ((1 << 64) - 1)


def main():
    rows = [power_of_five_significand(exponent) for exponent in range(MIN_EXPONENT, MAX_EXPONENT + 1)]
    output = open(sys.argv[1], "w")
    try:
        print("/* Generated by tools/generate_decimal_powers_of_five.py. */", file=output)
        print("/* The 128-bit significands of the powers of five 5^q for q in [-342, 308]:", file=output)
        print("   5^q shifted to [2^127, 2^128) and truncated for q >= 0; for q < 0, the", file=output)
        print("   reciprocal floor(2^b / 5^-q) + 1 with b = bit_length(5^-q) + 127 when", file=output)
        print("   q >= -27 and b = 2 * bit_length(5^-q) + 128 otherwise, truncated to its", file=output)
        print("   top 128 bits. Each row holds the high and the low 64 bits. */", file=output)
        print("#ifndef TINYPY_COMPILER_GENERATED_DECIMAL_POWERS_OF_FIVE_H", file=output)
        print("#define TINYPY_COMPILER_GENERATED_DECIMAL_POWERS_OF_FIVE_H", file=output)
        print("", file=output)
        print("#define TINYPY_DECIMAL_POWER_OF_FIVE_MIN_EXPONENT (%d)" % MIN_EXPONENT, file=output)
        print("#define TINYPY_DECIMAL_POWER_OF_FIVE_MAX_EXPONENT %d" % MAX_EXPONENT, file=output)
        print("", file=output)
        print("static const uint64_t __tinypy_decimal_powers_of_five[TINYPY_DECIMAL_POWER_OF_FIVE_MAX_EXPONENT - TINYPY_DECIMAL_POWER_OF_FIVE_MIN_EXPONENT + 1][2] = {", file=output)
        lines = []
        for index in range(0, len(rows), 2):
            pair = rows[index:index + 2]
            lines.append("    " + " ".join("{UINT64_C(0x%016x), UINT64_C(0x%016x)}," % row for row in pair))
        lines[-1] = lines[-1].rstrip(",")
        for line in lines:
            print(line, file=output)
        print("};", file=output)
        print("", file=output)
        print("#endif", file=output)
    finally:
        output.close()


if __name__ == "__main__":
    main()
